"""Generate 5 ms upright LQR; Python + NumPy + SciPy, no MCU dependency."""
import json
from pathlib import Path
import numpy as np
from scipy.linalg import expm, solve_discrete_are

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'docs/reference/2026-10-17_LQR接入参数.json'
data = json.loads(source.read_text())
p = data['upright']
A, B = np.array(p['A']), np.array(p['B'])
Q, R = np.array(p["Q"]), np.array(p["R"])
Ts = .005
# Exact ZOH dynamics and exact integral cost, including the cross term N.
F = np.block([[A, B], [np.zeros((2, 8))]])
W = np.zeros((8, 8)); W[:6, :6] = Q; W[6:, 6:] = R
V = expm(np.block([[-F.T, W], [np.zeros((8, 8)), F]]) * Ts)
Phi = V[8:, 8:]
Wd = Phi.T @ V[:8, 8:]; Wd = (Wd + Wd.T) / 2
Ad, Bd = Phi[:6, :6], Phi[:6, 6:]
Qd, Rd, Nd = Wd[:6, :6], Wd[6:, 6:], Wd[:6, 6:]
P = solve_discrete_are(Ad, Bd, Qd, Rd, s=Nd)
K = np.linalg.solve(Rd + Bd.T @ P @ Bd, Bd.T @ P @ Ad + Nd.T)
# Validate the float32 values actually embedded in firmware.
K = K.astype(np.float32).astype(float)
rho = float(max(abs(np.linalg.eigvals(Ad - Bd @ K))))
assert rho < 1
out = dict(source=str(source.relative_to(ROOT)), source_commit=data['source_commit'],
           parameters=data['parameters'], Ts_s=Ts,
           state_order=['e_x','e_psi','theta','e_xdot','psi_dot','theta_dot'],
           input_order=['tau_L_Nm','tau_R_Nm'],
           method='ZOH dynamics, exact continuous integral cost with cross term Nd',
           validation='Ideal linear torque plant only; no measured motor dynamics/delay/nonlinear validation',
           spectral_radius_float32=rho)
for name, value in dict(Ad=Ad, Bd=Bd, Qd=Qd, Rd=Rd, Nd=Nd, Kd=K).items():
    out[name] = value.tolist()
(ROOT / 'docs/reference/LQR直立离散参数.json').write_text(json.dumps(out, indent=2, ensure_ascii=False)+'\n')
rows = ',\n'.join('    {'+', '.join(f'{v:.9e}f' for v in row)+'}' for row in K)
(ROOT / 'module/overlay_app/inc/lqr_gain.h').write_text(
    '/* Generated by tools/generate_lqr.py; ideal torque plant, not hardware validated. */\n'
    '#ifndef LQR_GAIN_H\n#define LQR_GAIN_H\n#define LQR_PERIOD_US 5000U\n'
    'static const float lqr_k[2][6] = {\n'+rows+'\n};\n#endif\n')
print(f'float32 closed-loop spectral radius: {rho:.12f}')
